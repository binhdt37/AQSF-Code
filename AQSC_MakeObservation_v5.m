function obs = AQSC_MakeObservation_v5(prev,trace,k,cfg)
cap=trace.Capacity_Mbps(k);
obs=[min(prev.Latency_ms/cfg.deadline_ms,2)/2, min(prev.Loss/.10,1), ...
 min(prev.Throughput_Mbps/max(cap,1),1), min(max((trace.CellEdgeSINR_dB(k)+10)/30,0),1), ...
 min(max(trace.Threat(k)+.10*sin(k*.7),0),1), trace.Anomaly(k), ...
 min(prev.CryptoUtil,1), min(max(trace.BackgroundCPU(k),0),1)];
end
